import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1080}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8769');
await page.waitForFunction(()=>window.lab?.frame?.t>0);
await page.screenshot({path:'evidence/desktop.png',fullPage:true});
const before=await page.evaluate(()=>window.lab.frame.actors[0].x);
await page.keyboard.down('KeyD');await page.waitForTimeout(650);await page.keyboard.up('KeyD');
const after=await page.evaluate(()=>window.lab.frame.actors[0].x);
if(after<=before+70)throw Error('movement failed');
await page.keyboard.press('KeyE');await page.waitForTimeout(150);
if(await page.evaluate(()=>window.lab.frame.active)!==2)throw Error('swap failed');
await page.keyboard.press('KeyK');await page.waitForTimeout(150);
await page.locator('#auto').click();await page.waitForTimeout(1200);
await page.screenshot({path:'evidence/combat.png',fullPage:true});
await page.locator('#renderMode').selectOption('rect');
await page.waitForFunction(()=>window.lab.frame.commands>1000);
await page.screenshot({path:'evidence/rectangles.png',fullPage:true});
const rect=await page.evaluate(()=>({commands:window.lab.frame.commands,lua_ms:window.lab.frame.lua_ms,record:window.lab.records.at(-1)}));
await page.locator('#renderMode').selectOption('sprite');await page.locator('#density').selectOption('20');
await page.waitForFunction(()=>window.lab.frame.total===60);
await page.locator('#pause').click();await page.waitForTimeout(100);
const t=await page.evaluate(()=>window.lab.frame.t);await page.waitForTimeout(200);
if(await page.evaluate(()=>window.lab.frame.t)!==t)throw Error('pause failed');
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'evidence/mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw Error('mobile overflow');
const result={errors,movement:{before,after},rect,checks:['boot','keyboard movement','swap','attack','auto combat','Lua rectangle rendering','density 20','pause','mobile width']};
await fs.writeFile('evidence/browser-test.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));await browser.close();
if(errors.length)process.exit(1);
