import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';

const base=process.env.LAB_URL||'http://127.0.0.1:9124';
const load=async name=>JSON.parse(await readFile('content/'+name,'utf8'));
const index=await load('field-sprite-index.json');
const spawns=(await load('enemy-spawns.json')).nodes;
const byNode=new Map();
for(const species of index.species)for(const [node,count] of species.places){
 if(!byNode.has(node))byNode.set(node,new Map());
 byNode.get(node).set(species.id,count);
}
assert.equal(byNode.size,Object.keys(spawns).length);
for(const [node,placements] of Object.entries(spawns)){
 const counts=new Map();
 for(const p of placements)counts.set(p.art,(counts.get(p.art)||0)+1);
 assert.deepEqual(counts,byNode.get(node),node);
}
const browser=await chromium.launch({channel:'chrome'});
try{
 const page=await browser.newPage();
 await page.goto(base);
 await page.waitForFunction(()=>window.lab?.frame);
 await page.locator('#importSave').setInputFiles('evidence/fontaine-wildlife-save.json');
 await page.waitForFunction(()=>window.lab.frame.story?.node==='fontaine-hub');
 await page.evaluate(()=>document.activeElement.blur());
 await page.keyboard.press('KeyM');
 await page.locator('#worldAtlas').waitFor();
 const link=page.locator('#atlasFieldEnemyGuide'),node='fontaine-field';
 const atlasDaily=page.locator('#atlasDaily');
 await page.locator('#atlasField').selectOption('fontaine-hub');
 await atlasDaily.locator('summary').click();
 const authored=(await load('daily-quests.json')).quests.filter(q=>q.hub==='fontaine-hub');
 assert.deepEqual(await atlasDaily.locator('a').allTextContents(),authored.map(q=>q.name));
 assert((await atlasDaily.innerText()).includes('受付・報告'));
 await page.locator('#atlasField').selectOption(node);
 await page.waitForFunction(()=>document.querySelector('#atlasDailyLinks').textContent.includes('対象の敵が出現'));
 const dailyLink=atlasDaily.locator('a').first(),dailyName=await dailyLink.innerText();
 await page.locator('#worldAtlas').screenshot({path:'evidence/atlas-fontaine-daily-quests.png'});
 const popup=page.waitForEvent('popup');
 await dailyLink.click();
 const dailyGuide=await popup;
 await dailyGuide.waitForFunction(name=>document.querySelector('#name')?.textContent===name,dailyName);
 await dailyGuide.close();
 await link.waitFor();
 assert((await link.innerText()).includes('（'+spawns[node].length+'体）'));
 const opened=page.waitForEvent('popup');
 await link.click();
 const guide=await opened;
 const choices=guide.locator('#species');
 await guide.waitForFunction(()=>document.querySelector('#source')?.dataset.art);
 assert.deepEqual(await choices.locator('option').evaluateAll(options=>options.map(o=>o.value)),[...byNode.get(node).keys()]);
 for(const [id,count] of byNode.get(node)){
  await choices.selectOption(id);
  await guide.waitForFunction(value=>document.querySelector('#source').dataset.art===value,id);
  assert.equal(await guide.locator('#place').inputValue(),node);
  assert.equal(await guide.locator('#count').innerText(),'この地点に'+count+'体配置。地図を開いたときの進行状況では、入場時に'+count+'体出現。');
  const map=new URL(await guide.locator('#fieldMap').getAttribute('href'),base);
  assert.equal(map.searchParams.get('node'),node);
  assert.equal(map.searchParams.get('species'),id);
 }
 await guide.locator('#scope a').click();
 await guide.waitForFunction(()=>document.querySelector('#source')?.dataset.art);
 assert.equal(await choices.locator('option').count(),index.species.length);
 await page.locator('#atlasField').selectOption('fontaine-hub');
 await link.waitFor({state:'hidden'});
 assert.equal(await link.getAttribute('href'),null);
 await page.locator('#atlasField').selectOption('fon-emilie-scent-shore');
 await link.waitFor();
 await page.waitForFunction(()=>document.querySelector('#atlasFieldEnemyGuide').textContent.includes('今入ると0体／全配置1体'));
 const shore=page.waitForEvent('popup');
 await link.click();
 const shoreGuide=await shore;
 await shoreGuide.waitForFunction(()=>document.querySelector('#source')?.dataset.art==='armored-crab');
 assert((await shoreGuide.locator('#count').innerText()).includes('入場時に0体出現。 関連する依頼「旅の香りを、ひとしずく」'));
 await shoreGuide.locator('#fieldMap').click();
 await shoreGuide.waitForFunction(()=>window.mapArt?.ready);
 assert.match(await shoreGuide.locator('#status').innerText(),/入場配置.*敵配置 0体/);
 await shoreGuide.close();
 await guide.close();
 await page.bringToFront();
 await page.evaluate(()=>document.activeElement.blur());
 await page.keyboard.press('KeyM');
 await page.locator('#importSave').setInputFiles('evidence/liyue-crux-one-cargo-save.json');
 await page.waitForFunction(()=>window.lab.frame.story?.node==='liyue-harbor');
 await page.evaluate(()=>document.activeElement.blur());
 await page.keyboard.press('KeyM');
 await page.locator('#atlasField').selectOption('liyue-crux-wharf');
 await page.waitForFunction(()=>window.lab.frame.worldMap?.selected?.id==='liyue-crux-wharf');
 assert.match(await link.innerText(),/今入ると2体／全配置4体/);
 const wharf=page.waitForEvent('popup');
 await link.click();
 const wharfGuide=await wharf;
 await wharfGuide.waitForFunction(()=>document.querySelector('#source')?.dataset.art);
 const labels=await wharfGuide.locator('#species option').allTextContents();
 assert(labels[0].includes('入場時 1体')&&labels.at(-1).includes('現在は出現しない'));
 await wharfGuide.selectOption('#species','hilichurl');
 await wharfGuide.locator('#fieldMap').click();
 await wharfGuide.waitForFunction(()=>window.mapArt?.ready);
 assert.deepEqual(await wharfGuide.locator('#liveSubject option').evaluateAll(opts=>opts.map(o=>o.value)),['','liyue-crux-rocks','liyue-crux-ledge']);
 assert.equal(await wharfGuide.locator('#liveSubject').inputValue(),'liyue-crux-rocks');
 assert.match(await wharfGuide.locator('#status').innerText(),/入場配置.*敵配置 2体/);
 await wharfGuide.locator('#rect').screenshot({path:'evidence/liyue-crux-recovered-field.png'});
 console.log(byNode.size+' placement lists match; quest snapshots show 0 and 2 exact individuals in the field preview.');
}finally{await browser.close()}
