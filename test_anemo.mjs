import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1080}});const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8769');await page.waitForFunction(()=>window.lab?.frame);
await page.locator('[data-action="boss_anemo"]').click();
await page.waitForFunction(()=>window.lab.frame.boss?.phase==='shielded');
await page.screenshot({path:'evidence/anemo-shell.png',fullPage:true});
await page.waitForFunction(()=>window.lab.frame.boss?.phase==='clap_warning');
await page.screenshot({path:'evidence/anemo-warning.png',fullPage:true});
await page.waitForFunction(()=>window.lab.frame.boss?.phase==='exposed');
await page.locator('#auto').click();
await page.waitForFunction(()=>window.lab.frame.boss?.hp<300,null,{timeout:20000});
const hp=await page.evaluate(()=>window.lab.frame.boss.hp);
await page.locator('[data-action="town"]').click();
await page.waitForFunction(()=>window.lab.frame.campaign?.zone==='town'&&!window.lab.frame.boss);
if(errors.length)throw Error(errors.join('\n'));
await fs.writeFile('evidence/anemo-browser.json',JSON.stringify({errors,exposedDamageVerified:true,hp,returnVerified:true},null,2));
await browser.close();console.log('Anemo browser entry, telegraph, exposure damage, exit passed');
