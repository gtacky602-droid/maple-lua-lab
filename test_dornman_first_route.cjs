const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({channel:'chrome'});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  await page.goto(process.env.LAB_URL||'http://127.0.0.1:9118');
  await page.waitForFunction(()=>window.lab?.frame);
  await page.locator('#importSave').setInputFiles('work/dornman-first-ascent.json');
  await page.waitForFunction(()=>window.lab.frame.story?.node==='dornman-camp');
  await page.evaluate(()=>document.activeElement.blur());
  await page.keyboard.press('KeyM');
  await page.locator('#worldAtlas').waitFor();
  await page.locator('#atlasField').selectOption('dornman-flag-trestle');
  await page.waitForFunction(()=>window.lab.frame.worldMap?.selected?.id==='dornman-flag-trestle');
  await page.locator('#atlasItineraryStops li button').first().waitFor();
  const list=page.locator('#atlasItineraryStops li button');
  assert.equal(await list.count(),2);
  assert.match(await list.nth(0).innerText(),/潮風の見晴らし道.*必要Lv160/);
  assert.match(await list.nth(1).innerText(),/合図旗の渡り廊下.*昇降機.*必要Lv168/);
  await page.locator('#atlasItinerary').screenshot({path:'evidence/dornman-first-ascent.png'});
  await page.keyboard.press('Escape');
  await page.locator('#importSave').setInputFiles('evidence/dornman-map-lv167.json');
  await page.waitForFunction(()=>window.lab.frame.progression?.level===167);
  await page.evaluate(()=>document.activeElement.blur());
  await page.keyboard.press('KeyM');
  await page.locator('#worldAtlas').waitFor();
  await page.locator('#atlasField').selectOption('dornman-flag-trestle');
  const barrier=page.locator('#atlasFirstBlocked');
  await barrier.waitFor();
  assert.match(await barrier.innerText(),/潮風の見晴らし道 → 合図旗の渡り廊下（必要Lv168）/);
  const preview=new URL(await barrier.locator('a').getAttribute('href'),page.url());
  assert.equal(preview.searchParams.get('node'),'dornman-wind-stairs');
  assert.equal(preview.searchParams.get('to'),'dornman-flag-trestle');
  await page.locator('#atlasItinerary').screenshot({path:'evidence/dornman-before-lift.png'});
  await barrier.getByRole('button',{name:'潮風の見晴らし道までの道順を見る'}).click();
  await page.waitForFunction(()=>window.lab.frame.worldMap?.selected?.id==='dornman-wind-stairs');
  await barrier.waitFor({state:'hidden'});
  assert.equal(await list.count(),1);
  await page.keyboard.press('Escape');
  await page.locator('#importSave').setInputFiles('work/dornman-entry-level.json');
  await page.waitForFunction(()=>window.lab.frame.progression?.level===1);
  await page.evaluate(()=>document.activeElement.blur());
  await page.keyboard.press('KeyM');
  await page.locator('#worldAtlas').waitFor();
  await page.locator('#atlasField').selectOption('dornman-wind-stairs');
  await barrier.waitFor();
  assert.match(await barrier.textContent(),/入口拠点 → 潮風の見晴らし道（必要Lv160）/);
  assert.equal(await barrier.locator('button').count(),0);
  await page.keyboard.press('Escape');
  await page.locator('#importSave').setInputFiles('evidence/dornman-map-shortcut.json');
  await page.waitForFunction(()=>window.lab.frame.progression?.level===168);
  await page.evaluate(()=>document.activeElement.blur());
  await page.keyboard.press('KeyM');
  await page.locator('#worldAtlas').waitFor();
  await page.locator('#atlasField').selectOption('dornman-flag-trestle');
  await page.waitForFunction(()=>window.lab.frame.worldMap?.selected?.id==='dornman-flag-trestle');
  assert.equal(await list.count(),1);
  assert(await barrier.isHidden());
  console.log('Immediate Lv1 gate, second-leg Lv167 gate and published Lv168 shortcut save verified.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
