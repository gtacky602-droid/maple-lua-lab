"""Publish measured Lua payload sizes and color errors for the placement preview."""
import hashlib
import json
from pathlib import Path
if __package__:
    from .scenery_locations import measurement_key
else:
    from scenery_locations import measurement_key

ROOT = Path(__file__).resolve().parents[1]


def measurements():
    result = {}
    aliases = {}
    bench_path = ROOT / 'evidence/scenery-local-decode-cost.json'
    bench = json.loads(bench_path.read_text('utf8')) if bench_path.exists() else {}
    for report in sorted((ROOT / 'evidence').glob('*-background-compression.json')):
        data = json.loads(report.read_text(encoding='utf8'))
        scenes = data['scenes']
        prefix = report.name.removesuffix('-background-compression.json')
        prefix = 'fon-beryl' if prefix == 'beryl' else prefix
        manifest = ROOT / 'assets' / f'{prefix}-background-generation.json'
        bundle = ROOT / 'assets' / (prefix+'-native-backgrounds.lua')
        has_benchmark = (bench.get('codecSha256') == data['codecSha256'] and
                         bench.get('bundleSha256',{}).get(bundle.name) == hashlib.sha256(bundle.read_bytes()).hexdigest())
        for row in json.loads(manifest.read_text(encoding='utf8'))['scenes']:
            scene = scenes[row['source']]
            key = measurement_key(row)
            if key in result or key in aliases:
                raise ValueError('Multiple background measurements for '+key)
            result[key] = {
                'bundle': prefix+'-native-backgrounds.lua',
                'bytes': scene['baseSelectedBytes'] + scene['detailSelectedBytes'],
                'error': {tier['rectangles']: tier['meanAbsoluteRgbErrorToReference']
                          for tier in scene['tiers']},
            }
            if row.get('sharedNodes'):
                result[key]['locations'] = 1 + len(row['sharedNodes'])
            costs = bench.get('scenes',{}).get(key) if has_benchmark else None
            if costs:
                result[key]['decode'] = {
                    tier: {'ms': values['medianDecodeMs'], 'kib': values['medianRetainedLuaKiB']}
                    for tier, values in costs.items()
                }
            for node in row.get('sharedNodes', []):
                node = measurement_key(row,node)
                if node in result or node in aliases:
                    raise ValueError('Multiple background measurements for '+node)
                aliases[node] = key
    return result, aliases


if __name__ == '__main__':
    lines = ['// Generated by tools/build_scenery_measurements.py.', 'export const backgroundMeasurements = {']
    rows, aliases = measurements()
    for node, row in rows.items():
        lines.append('  '+json.dumps(node)+': '+json.dumps(row)+',')
    lines.append('};')
    for node, source in aliases.items():
        lines.append(f'backgroundMeasurements[{json.dumps(node)}] = backgroundMeasurements[{json.dumps(source)}];')
    (ROOT / 'scenery-measurements.js').write_text('\n'.join(lines)+'\n', encoding='utf8')
