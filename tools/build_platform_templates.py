"""Export the lab's static platform geometry as a stand-alone, on-demand Lua module."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(nodes):
    def literal(value):
        if isinstance(value, str):
            return '"' + "".join(
                chr(byte) if 32 <= byte < 127 and byte not in (34, 92) else f"\\{byte:03d}"
                for byte in value.encode("utf8")) + '"'
        return json.dumps(value, allow_nan=False)

    def array(values):
        return "{" + ",".join(literal(v) for v in values) + "}"

    rows, layouts, refs = {}, {}, {}
    for node in nodes:
        layout = []
        for platform in node["platforms"]:
            keys = set(platform) - {"x", "y", "w"}
            coords = [platform[k] for k in ("x", "y", "w")]
            if any(type(v) not in (int, float) for v in coords):
                raise ValueError((node["id"], platform))
            flags = sorted(keys)
            if any(type(platform[k]) not in (bool, int, str) or not k.isascii() or not k.isidentifier() for k in flags):
                raise ValueError((node["id"], platform))
            row = array(coords + [value for key in flags for value in (key, platform[key])])
            layout.append(rows.setdefault(row, len(rows) + 1))
        if node["id"] in refs:
            raise ValueError(node["id"])
        refs[node["id"]] = layouts.setdefault(tuple(layout), len(layouts) + 1)

    lines = ["-- Generated by tools/build_platform_templates.py", "local rows = {"]
    lines.extend(row + "," for row in rows)
    lines.extend(["}", "local layouts = {"])
    lines.extend(array(layout) + "," for layout in layouts)
    lines.extend(["}", "local maps = {"])
    lines.extend(f"[{literal(key)}]={ref}," for key, ref in refs.items())
    lines.append("""}
return function(mapId)
    local index = maps[mapId]
    if not index then return nil end
    local platforms = {}
    for i, rowId in ipairs(layouts[index]) do
        local row = rows[rowId]
        local platform = {x=row[1], y=row[2], w=row[3]}
        for j = 4, #row, 2 do platform[row[j]] = row[j+1] end
        platforms[i] = platform
    end
    return platforms
end""")
    return ("\n".join(lines) + "\n").encode(), len(layouts), len(rows)


if __name__ == "__main__":
    nodes = json.loads((ROOT / "content/story-graph.json").read_bytes())["nodes"]
    module, _, _ = build(nodes)
    (ROOT / "content/platform-templates.lua").write_bytes(module)
